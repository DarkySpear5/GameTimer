CURRENT_LANG = "en"


def apply_language_global(code):
    global CURRENT_LANG
    CURRENT_LANG = code if code in TRANSLATIONS else "en"


def tr(key, **kwargs):
    lang_dict = TRANSLATIONS.get(CURRENT_LANG, {})
    text = lang_dict.get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def tr_genre(genre_key):
    lang_dict = GENRE_TRANSLATIONS.get(CURRENT_LANG, {})
    return lang_dict.get(genre_key) or GENRE_TRANSLATIONS["en"].get(genre_key, genre_key)
